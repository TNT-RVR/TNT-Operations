describe('getUpcomingEvents / getAllEvents (get_upcoming_events)', () => {
  const now = new Date('2026-07-22T09:00:00Z')
  const batch: Batch = {
    id: 'b1',
    name: 'Batch One',
    incubatorName: 'Inc A',
    startDate: '2026-07-20',
    vaponaIn: '2026-07-22', // 0  → urgent
    vaponaOut: '2026-07-20', // -2 → dropped (before -1)
    airOut: '2026-07-25', // 3
    earliestCool: '2026-08-21', // 30 → boundary, kept
    estimatedRelease: '2026-08-30', // 39 → dropped (> 30)
    latestRelease: '2026-07-21', // -1 → urgent, kept
  }

  it('keeps events in [-1, lookahead], sorted by days away', () => {
    const events = getUpcomingEvents(batch, now)
    expect(events.map((e) => e.label)).toEqual([
      'Latest Release',
      'Vapona In',
      'Air Out',
      'Earliest Cool',
    ])
    expect(events.map((e) => e.daysAway)).toEqual([-1, 0, 3, 30])
    expect(events.map((e) => e.urgent)).toEqual([true, true, false, false])
    expect(events[0]).toMatchObject({ batchName: 'Batch One', batchId: 'b1', incubatorName: 'Inc A' })
  })

  it('respects a shorter lookahead window', () => {
    const events = getUpcomingEvents(batch, now, 5)
    expect(events.map((e) => e.label)).toEqual(['Latest Release', 'Vapona In', 'Air Out'])
  })

  it('merges + sorts across batches', () => {
    const b2: Batch = { id: 'b2', name: 'Batch Two', airOut: '2026-07-23' } // 1
    const all = getAllEvents([batch, b2], now)
    expect(all.map((e) => e.daysAway)).toEqual([-1, 0, 1, 3, 30])
  })
})

