describe('incubation milestones', () => {
  const trays = [
    { incubatorId: 'i1', status: 'active', inDate: '2026-06-01' },
    { incubatorId: 'i1', status: 'active', inDate: '2026-06-01' },
    { incubatorId: 'i1', status: 'active', inDate: '2026-06-03' },
    { incubatorId: 'i1', status: 'released', inDate: '2025-01-01' }, // ignored
    { incubatorId: 'i2', status: 'active', inDate: null },
  ]

  it('prefers the explicit start date', () => {
    expect(incubationStartFor({ id: 'i1', incubationStart: '2026-07-10' }, trays)).toBe('2026-07-10')
  })

  it('treats "none" as schedule removed, not as a date to derive', () => {
    expect(incubationStartFor({ id: 'i1', incubationStart: 'none' }, trays)).toBeNull()
  })

  it('falls back to the most common in-date among ACTIVE trays', () => {
    expect(incubationStartFor({ id: 'i1', incubationStart: null }, trays)).toBe('2026-06-01')
  })

  it('is null when nothing gives a start date', () => {
    expect(incubationStartFor({ id: 'i2', incubationStart: '' }, trays)).toBeNull()
  })

  it('places day N at start + (N-1), so day 1 is the start', () => {
    const evs = milestoneEvents([{ id: 'i1', name: 'Inc 1', incubationStart: '2026-06-01' }], [])
    expect(evs[0]).toMatchObject({ day: 1, label: 'Incubation Start', date: '2026-06-01' })
    expect(evs.find((e) => e.day === 7)?.date).toBe('2026-06-07')
    expect(evs.find((e) => e.day === 23)?.date).toBe('2026-06-23')
    expect(evs.find((e) => e.day === 37)?.date).toBe('2026-07-07') // crosses the month
  })

  it('skips incubators with no start date', () => {
    const evs = milestoneEvents(
      [
        { id: 'i1', name: 'Inc 1', incubationStart: '2026-06-01' },
        { id: 'i2', name: 'Inc 2', incubationStart: null },
      ],
      [],
    )
    expect(new Set(evs.map((e) => e.incubatorId))).toEqual(new Set(['i1']))
  })

  it('skips an incubator that is switched off', () => {
    const evs = milestoneEvents(
      [
        { id: 'i1', name: 'Inc 1', incubationStart: '2026-06-01', tempMode: 'incubation' },
        { id: 'i2', name: 'Inc 2', incubationStart: '2026-06-01', tempMode: 'off' },
      ],
      [],
    )
    expect(new Set(evs.map((e) => e.incubatorId))).toEqual(new Set(['i1']))
  })

  it('does not invent a run from a stray tray left in an off incubator', () => {
    // The live case: Incubator 1 off, no start date, one active tray still
    // assigned to it. The tray fallback would otherwise plot Day 1 → Day 37.
    const trays = [{ incubatorId: 'i1', status: 'active', inDate: '2026-08-04' }]
    expect(milestoneEvents([{ id: 'i1', name: 'Inc 1', incubationStart: null, tempMode: 'off' }], trays)).toEqual([])
    // Same data, incubator actually running → the fallback is still wanted.
    expect(
      milestoneEvents([{ id: 'i1', name: 'Inc 1', incubationStart: null, tempMode: 'incubation' }], trays).length,
    ).toBe(INCUBATION_MILESTONES.length)
  })

  it('keeps plotting through holding and cool storage — a run continues while cooling', () => {
    for (const tempMode of ['holding', 'cool_storage']) {
      const evs = milestoneEvents([{ id: 'i1', name: 'Inc 1', incubationStart: '2026-06-01', tempMode }], [])
      expect(evs.length).toBe(INCUBATION_MILESTONES.length)
    }
  })

  it('assumes running when the caller does not model modes', () => {
    // Back-compat: callers passing no tempMode must keep their milestones.
    expect(milestoneEvents([{ id: 'i1', name: 'Inc 1', incubationStart: '2026-06-01' }], []).length).toBe(
      INCUBATION_MILESTONES.length,
    )
  })

  it('exports all-day VEVENTs with an exclusive DTEND', () => {
    const evs = milestoneEvents([{ id: 'i1', name: 'Inc 1', incubationStart: '2026-06-01' }], [])
    const ics = milestonesToIcs(evs.slice(0, 1), '2026-08-04T12:00:00.000Z')
    expect(ics).toContain('BEGIN:VCALENDAR')
    expect(ics).toContain('DTSTART;VALUE=DATE:20260601')
    expect(ics).toContain('DTEND;VALUE=DATE:20260602')
    expect(ics).toContain('SUMMARY:Inc 1 — Incubation Start (Day 1)')
    expect(ics).toContain('DTSTAMP:20260804T120000Z')
    expect(ics.endsWith('END:VCALENDAR')).toBe(true)
    expect(ics.split('\r\n').length).toBeGreaterThan(5) // CRLF line endings
  })
})

describe('holding-day reporting', () => {
  // Fixed UTC-day mapper keeps these tests timezone-independent.
  const toYmd = (iso: string) => iso.slice(0, 10)

  const readings = [
    { incubatorId: 'i1', at: '2026-06-01T06:00:00Z', tempC: 30 },
    { incubatorId: 'i1', at: '2026-06-01T18:00:00Z', tempC: 32 }, // mean 31 → incubating
    { incubatorId: 'i1', at: '2026-06-02T06:00:00Z', tempC: 14 },
    { incubatorId: 'i1', at: '2026-06-02T18:00:00Z', tempC: 16 }, // mean 15 → holding
    { incubatorId: 'i2', at: '2026-06-01T06:00:00Z', tempC: 4 }, // cool storage, not holding
    { incubatorId: 'i3', at: '2026-06-01T06:00:00Z', tempC: 20 }, // off / shop ambient
  ]

  it('averages per incubator per day', () => {
    const means = dailyMeanTempByIncubator(readings, toYmd)
    expect(means.get('i1')?.get('2026-06-01')).toBe(31)
    expect(means.get('i1')?.get('2026-06-02')).toBe(15)
  })

  it('counts ONLY days in the holding band', () => {
    const held = holdingDays(dailyMeanTempByIncubator(readings, toYmd))
    expect([...(held.get('i1') ?? [])]).toEqual(['2026-06-02'])
  })

  it('ignores cool storage and an incubator that is simply off', () => {
    const held = holdingDays(dailyMeanTempByIncubator(readings, toYmd))
    // 4 C is below the band; 20 C (shop ambient, switched off) is above it.
    expect(held.get('i2')).toBeUndefined()
    expect(held.get('i3')).toBeUndefined()
  })

  it('uses the day MEAN, so a brief dip into the band is not a holding day', () => {
    const dip = [
      { incubatorId: 'i1', at: '2026-06-03T06:00:00Z', tempC: 30 },
      { incubatorId: 'i1', at: '2026-06-03T07:00:00Z', tempC: 15 }, // door open
      { incubatorId: 'i1', at: '2026-06-03T08:00:00Z', tempC: 30 },
    ]
    expect(holdingDays(dailyMeanTempByIncubator(dip, toYmd)).get('i1')).toBeUndefined()
  })

  it('reports nothing when there are no readings', () => {
    expect(holdingDays(dailyMeanTempByIncubator([], toYmd)).size).toBe(0)
  })

  it('runWindow spans the start through the last milestone', () => {
    expect(runWindow('2026-06-01')).toEqual({ from: '2026-06-01', to: '2026-07-07' })
  })
})

describe('developmental stages', () => {
  it('parses the first day out of each stage label', () => {
    expect(stageStartDay('Day 1 — Worm/Larva')).toBe(1)
    expect(stageStartDay('Day 8–9 — Pupal')).toBe(8)
    expect(stageStartDay('Day 17–18 — Male emergence')).toBe(17)
    expect(stageStartDay('nonsense')).toBeNull()
  })

  it('expects the latest stage whose day has been reached', () => {
    expect(expectedStageForDay(1)).toBe('Day 1 — Worm/Larva')
    expect(expectedStageForDay(4)).toBe('Day 3 — Whitening') // between stages → the earlier one
    expect(expectedStageForDay(9)).toBe('Day 8–9 — Pupal')
    expect(expectedStageForDay(13)).toBe('Day 13 — Male dark eye / Female red eye')
    expect(expectedStageForDay(25)).toBe('Day 20 — Female emergence') // past the end
  })

  it('has no expectation before day 1', () => {
    expect(expectedStageForDay(0)).toBeNull()
    expect(expectedStageForDay(null)).toBeNull()
    expect(expectedStageForDay(undefined)).toBeNull()
  })

  it('measures how far an observation is from the schedule', () => {
    // On day 13 the tray should be at "Male dark eye"; seeing "Pink-Eyed" is one behind.
    expect(stageDelta('Day 13 — Male dark eye / Female red eye', 13)).toBe(0)
    expect(stageDelta('Day 10 — Pink-Eyed', 13)).toBe(-1)
    // Day 14-15 sits between, so Male emergence is TWO stages ahead of day 13.
    expect(stageDelta('Day 17–18 — Male emergence', 13)).toBe(2)
  })

  it('returns no delta for an unknown stage or unknown day', () => {
    expect(stageDelta('Day 13 — Male dark eye / Female red eye', null)).toBeNull()
    expect(stageDelta('made up stage', 13)).toBeNull()
  })
})
